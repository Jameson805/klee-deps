static inline void overwrite_suffix(unsigned char *dest, size_t dest_len,
                                    const unsigned char *suffix, size_t suffix_len)
{
    if (suffix_len > dest_len) {
        suffix += suffix_len - dest_len;
        suffix_len = dest_len;
    }
    memcpy(dest + dest_len - suffix_len, suffix, suffix_len);
}

static br_rsa_private_key load_symbolic_rsa_key(unsigned char *dp_full,
                                                unsigned char *dq_full,
                                                const unsigned char *dp_suffix,
                                                size_t dp_suffix_len,
                                                const unsigned char *dq_suffix,
                                                size_t dq_suffix_len)
{
    br_rsa_private_key key;

    memcpy(dp_full, RSA_DP_BYTES, sizeof(RSA_DP_BYTES));
    memcpy(dq_full, RSA_DQ_BYTES, sizeof(RSA_DQ_BYTES));
    overwrite_suffix(dp_full, sizeof(RSA_DP_BYTES), dp_suffix, dp_suffix_len);
    overwrite_suffix(dq_full, sizeof(RSA_DQ_BYTES), dq_suffix, dq_suffix_len);

    key.n_bitlen = 1024;
    key.p = (unsigned char *) RSA_P_BYTES;
    key.plen = sizeof(RSA_P_BYTES);
    key.q = (unsigned char *) RSA_Q_BYTES;
    key.qlen = sizeof(RSA_Q_BYTES);
    key.dp = dp_full;
    key.dplen = sizeof(RSA_DP_BYTES);
    key.dq = dq_full;
    key.dqlen = sizeof(RSA_DQ_BYTES);
    key.iq = (unsigned char *) RSA_IQ_BYTES;
    key.iqlen = sizeof(RSA_IQ_BYTES);
    return key;
}

static void normalize_ciphertext(unsigned char *dst,
                                 const unsigned char *src,
                                 size_t len)
{
    unsigned char reduced[sizeof(RSA_N_BYTES)];
    int ge = 0;
    int lt = 0;
    unsigned int borrow = 0;

    runner_copy_bytes(dst, src, len);
    if (len != sizeof(RSA_N_BYTES)) {
        return;
    }
    for (size_t i = 0; i < sizeof(RSA_N_BYTES); i++) {
        unsigned int a = dst[sizeof(RSA_N_BYTES) - 1 - i];
        unsigned int b = RSA_N_BYTES[sizeof(RSA_N_BYTES) - 1 - i];
        unsigned int diff = a - b - borrow;
        reduced[sizeof(RSA_N_BYTES) - 1 - i] = (unsigned char) diff;
        borrow = (diff >> 8) & 1;
    }
    for (size_t i = 0; i < sizeof(RSA_N_BYTES); i++) {
        ge |= (!lt & (dst[i] > RSA_N_BYTES[i]));
        lt |= (!ge & (dst[i] < RSA_N_BYTES[i]));
    }
    if (ge || !lt) {
        runner_copy_bytes(dst, reduced, len);
    }
}

