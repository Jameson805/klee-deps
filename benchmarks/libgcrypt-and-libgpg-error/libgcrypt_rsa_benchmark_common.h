static inline void overwrite_suffix(unsigned char *dest, size_t dest_len,
                                    const unsigned char *suffix, size_t suffix_len)
{
    if (suffix_len > dest_len) {
        suffix += suffix_len - dest_len;
        suffix_len = dest_len;
    }

    memcpy(dest + dest_len - suffix_len, suffix, suffix_len);
}

static int libgcrypt_rsa_init(void)
{
    if (!gcry_check_version(NULL)) {
        fprintf(stderr, "libgcrypt init failed\n");
        return 0;
    }
    gcry_control(GCRYCTL_DISABLE_SECMEM, 0);
    gcry_control(GCRYCTL_INITIALIZATION_FINISHED, 0);
    return 1;
}

static gcry_error_t scan_mpi(gcry_mpi_t *mpi_value,
                             const unsigned char *bytes,
                             size_t len)
{
    return gcry_mpi_scan(mpi_value, GCRYMPI_FMT_USG, bytes, len, NULL);
}

static gcry_sexp_t load_symbolic_private_key(const unsigned char *d_suffix,
                                             size_t d_suffix_len)
{
    unsigned char d_full[sizeof(RSA_D_BYTES)];
    gcry_sexp_t key = NULL;
    gcry_mpi_t mpi_n = NULL;
    gcry_mpi_t mpi_e = NULL;
    gcry_mpi_t mpi_d = NULL;
    gcry_mpi_t mpi_p = NULL;
    gcry_mpi_t mpi_q = NULL;
    gcry_mpi_t mpi_u = NULL;
    gcry_error_t err;

    memcpy(d_full, RSA_D_BYTES, sizeof(d_full));
    overwrite_suffix(d_full, sizeof(d_full), d_suffix, d_suffix_len);

    err = scan_mpi(&mpi_n, RSA_N_BYTES, sizeof(RSA_N_BYTES));
    if (err) {
        goto cleanup;
    }
    err = scan_mpi(&mpi_e, RSA_E_BYTES, sizeof(RSA_E_BYTES));
    if (err) {
        goto cleanup;
    }
    err = scan_mpi(&mpi_d, d_full, sizeof(d_full));
    if (err) {
        goto cleanup;
    }
    err = scan_mpi(&mpi_p, RSA_P_BYTES, sizeof(RSA_P_BYTES));
    if (err) {
        goto cleanup;
    }
    err = scan_mpi(&mpi_q, RSA_Q_BYTES, sizeof(RSA_Q_BYTES));
    if (err) {
        goto cleanup;
    }
    err = scan_mpi(&mpi_u, RSA_U_BYTES, sizeof(RSA_U_BYTES));
    if (err) {
        goto cleanup;
    }

    err = gcry_sexp_build(&key, NULL,
                          "(private-key(rsa(n %m)(e %m)(d %m)(p %m)(q %m)(u %m)))",
                          mpi_n, mpi_e, mpi_d, mpi_p, mpi_q, mpi_u);
    if (err) {
        key = NULL;
    }

cleanup:
    gcry_mpi_release(mpi_n);
    gcry_mpi_release(mpi_e);
    gcry_mpi_release(mpi_d);
    gcry_mpi_release(mpi_p);
    gcry_mpi_release(mpi_q);
    gcry_mpi_release(mpi_u);
    return key;
}

#if defined(LIBGCRYPT_RSA_DECRYPT_PKCS1) || \
    defined(LIBGCRYPT_RSA_DECRYPT_OAEP) || \
    defined(LIBGCRYPT_RSA_DECRYPT_RAW)
static gcry_sexp_t build_decrypt_data(const unsigned char *ciphertext,
                                      size_t ciphertext_len)
{
    gcry_sexp_t data = NULL;
    gcry_mpi_t mpi_ciphertext = NULL;
    gcry_error_t err;

    err = scan_mpi(&mpi_ciphertext, ciphertext, ciphertext_len);
    if (err) {
        return NULL;
    }

#if defined(LIBGCRYPT_RSA_DECRYPT_PKCS1)
    err = gcry_sexp_build(&data, NULL,
                          "(enc-val(flags pkcs1 no-blinding)(rsa(a %m)))",
                          mpi_ciphertext);
#elif defined(LIBGCRYPT_RSA_DECRYPT_OAEP)
    err = gcry_sexp_build(&data, NULL,
                          "(enc-val(flags oaep no-blinding)(hash-algo sha1)(rsa(a %m)))",
                          mpi_ciphertext);
#elif defined(LIBGCRYPT_RSA_DECRYPT_RAW)
    err = gcry_sexp_build(&data, NULL,
                          "(enc-val(flags raw no-blinding)(rsa(a %m)))",
                          mpi_ciphertext);
#else
#error "Define exactly one Libgcrypt RSA decrypt target macro."
#endif

    gcry_mpi_release(mpi_ciphertext);
    if (err) {
        gcry_sexp_release(data);
        return NULL;
    }
    return data;
}
#endif

